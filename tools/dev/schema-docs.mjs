// Builds src/interfaces/http/dev/playground-schema-docs.ts from the schema docs, so the playground's
// Schema tab can show each field's rule and the old field it comes from next to the live schema.
//   node tools/dev/schema-docs.mjs     (run again when docs/SCHEMA.md or the phase pages change)
// Sources: the field tables of docs/SCHEMA.md (device core), and the erDiagram blocks of the
// Phase 1 and Phase 5 pages (brands, customers, staff).
import { readFileSync, writeFileSync } from 'node:fs';

const clean = (s) => s.replace(/`/g, '').replace(/\*\*/g, '').replace(/\\\|/g, '|').trim();
const docs = {};

// docs/SCHEMA.md: "## 2. `trialDevices`", a description paragraph, then | Field | Type | Rule | From |.
const schema = readFileSync('docs/SCHEMA.md', 'utf8').split('\n');
let current = null;
for (let i = 0; i < schema.length; i++) {
  const line = schema[i];
  const head = /^## \d+\. `([A-Za-z]+)`/.exec(line);
  if (head) {
    current = docs[head[1]] = { about: '', fields: {} };
    for (let j = i + 1; j < schema.length && !schema[j].startsWith('|'); j++) {
      if (schema[j].trim()) { current.about = clean(schema[j]); break; }
    }
    continue;
  }
  if (line.startsWith('## ')) { current = null; continue; }
  if (!current || !line.startsWith('| `')) continue;
  const cells = line.split(/(?<!\\)\|/).slice(1, -1).map((c) => c.trim());
  if (cells.length < 4) continue;
  current.fields[clean(cells[0])] = { rule: clean(cells[2]), from: clean(cells[3]) };
}

// erDiagram blocks:  collection {  /  type name [PK|FK|UK] "note"
for (const page of ['docs/phases/phase-1-foundation.md', 'docs/phases/phase-5-accounts-and-staff.md']) {
  let inDiagram = false, entity = null;
  for (const line of readFileSync(page, 'utf8').split('\n')) {
    if (line.trim() === 'erDiagram') { inDiagram = true; continue; }
    if (inDiagram && line.trim() === '```') { inDiagram = false; entity = null; continue; }
    if (!inDiagram) continue;
    const open = /^\s+([a-zA-Z]+) \{$/.exec(line);
    if (open) { entity = docs[open[1]] ?? (docs[open[1]] = { about: '', fields: {} }); continue; }
    if (/^\s+\}$/.test(line)) { entity = null; continue; }
    const field = /^\s+\S+ (\w+)((?: (?:PK|FK|UK))*)(?: "([^"]*)")?/.exec(line);
    if (entity && field && !entity.fields[field[1]]) {
      const keys = field[2].trim().split(/\s+/).filter(Boolean).map((k) => ({ PK: 'primary key', FK: 'refers to another collection', UK: 'unique' })[k]);
      entity.fields[field[1]] = { rule: [...keys, field[3] ?? ''].filter(Boolean).join('; '), from: '' };
    }
  }
}

const body = JSON.stringify(docs, null, 2);
if (body.includes('`') || body.includes('${')) throw new Error('unexpected backtick in the docs data');
writeFileSync(
  'src/interfaces/http/dev/playground-schema-docs.ts',
  `/**
 * What the docs say about each field (its rule, and the old field it comes from), for the playground's
 * Schema tab. Generated by tools/dev/schema-docs.mjs from docs/SCHEMA.md and the Phase 1 and Phase 5
 * pages; run it again when they change.
 */
export const PLAYGROUND_SCHEMA_DOCS: Record<
  string,
  { about: string; fields: Record<string, { rule: string; from: string }> }
> = ${body};
`,
);
console.log(Object.entries(docs).map(([k, v]) => `${k}: ${Object.keys(v.fields).length}`).join(', '));
